#!/usr/bin/env node

import fs from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const pluginRoot = path.resolve(scriptDir, '..');
const checkOnly = process.argv.includes('--check');

const sourcePluginJsonPath = path.join(pluginRoot, '.claude-plugin', 'plugin.json');
const sourceHooksPath = path.join(pluginRoot, 'hooks', 'hooks.json');
const sourceAgentsDir = path.join(pluginRoot, 'agents');
const sourceCommandsDir = path.join(pluginRoot, 'commands');

const targetPluginJsonPath = path.join(pluginRoot, 'plugin.json');
const targetHooksPath = path.join(pluginRoot, 'hooks.json');
const targetAgentsDir = path.join(pluginRoot, 'copilot-agents');
const targetSkillsDir = path.join(pluginRoot, 'skills');

const updates = [];

function normalizeText(text) {
  return text.replace(/\r\n/g, '\n');
}

function extractFrontmatter(markdown, sourcePath) {
  const normalized = normalizeText(markdown);
  if (!normalized.startsWith('---\n')) {
    throw new Error(`Missing frontmatter in ${sourcePath}`);
  }

  const end = normalized.indexOf('\n---\n', 4);
  if (end === -1) {
    throw new Error(`Unterminated frontmatter in ${sourcePath}`);
  }

  return {
    frontmatter: normalized.slice(4, end),
    body: normalized.slice(end + 5),
  };
}

function getScalar(frontmatter, key) {
  const match = frontmatter.match(new RegExp(`^${key}:\\s*(.+)$`, 'm'));
  return match ? match[1].trim() : null;
}

function generatedBodyComment(relativeSourcePath) {
  return `<!-- Generated by scripts/sync-copilot-format.mjs from ${relativeSourcePath}. Edit the source file and rerun the generator. -->\n\n`;
}

async function ensureDir(dirPath) {
  if (!checkOnly) {
    await fs.mkdir(dirPath, { recursive: true });
  }
}

async function syncFile(filePath, contents) {
  const normalized = normalizeText(contents);
  let current = null;

  try {
    current = normalizeText(await fs.readFile(filePath, 'utf8'));
  } catch (error) {
    if (error.code !== 'ENOENT') {
      throw error;
    }
  }

  if (current === normalized) {
    return;
  }

  updates.push(path.relative(pluginRoot, filePath));
  if (!checkOnly) {
    await fs.mkdir(path.dirname(filePath), { recursive: true });
    await fs.writeFile(filePath, normalized, 'utf8');
  }
}

async function pruneDir(dirPath, expectedRelativePaths) {
  let entries = [];
  try {
    entries = await fs.readdir(dirPath, { withFileTypes: true });
  } catch (error) {
    if (error.code === 'ENOENT') {
      return;
    }
    throw error;
  }

  for (const entry of entries) {
    const entryPath = path.join(dirPath, entry.name);
    if (entry.isDirectory()) {
      await pruneDir(entryPath, expectedRelativePaths);
      const remaining = await fs.readdir(entryPath);
      if (remaining.length === 0 && !checkOnly) {
        await fs.rmdir(entryPath);
      }
      continue;
    }

    const relPath = path.relative(pluginRoot, entryPath).replace(/\\/g, '/');
    if (expectedRelativePaths.has(relPath)) {
      continue;
    }

    updates.push(relPath);
    if (!checkOnly) {
      await fs.unlink(entryPath);
    }
  }
}

async function listFiles(dirPath) {
  const entries = await fs.readdir(dirPath, { withFileTypes: true });
  return entries
    .filter((entry) => entry.isFile())
    .map((entry) => entry.name)
    .sort((left, right) => left.localeCompare(right));
}

async function buildCopilotManifest() {
  const sourcePlugin = JSON.parse(await fs.readFile(sourcePluginJsonPath, 'utf8'));
  const manifest = {
    ...sourcePlugin,
    agents: 'copilot-agents/',
    skills: ['skills/'],
    hooks: 'hooks.json',
  };

  await syncFile(targetPluginJsonPath, `${JSON.stringify(manifest, null, 2)}\n`);
}

async function buildHooks() {
  const hooks = normalizeText(await fs.readFile(sourceHooksPath, 'utf8'))
    .replace(/\$\{CLAUDE_PLUGIN_ROOT\}/g, '${PLUGIN_ROOT}');
  await syncFile(targetHooksPath, hooks);
}

async function buildAgents(expectedPaths) {
  const agentFiles = await listFiles(sourceAgentsDir);
  await ensureDir(targetAgentsDir);

  for (const fileName of agentFiles) {
    if (!fileName.endsWith('.md')) {
      continue;
    }

    const sourcePath = path.join(sourceAgentsDir, fileName);
    const relativeSourcePath = path.relative(pluginRoot, sourcePath).replace(/\\/g, '/');
    const markdown = await fs.readFile(sourcePath, 'utf8');
    const { frontmatter, body } = extractFrontmatter(markdown, relativeSourcePath);
    const targetPath = path.join(targetAgentsDir, fileName.replace(/\.md$/, '.agent.md'));
    const targetRelativePath = path.relative(pluginRoot, targetPath).replace(/\\/g, '/');
    const output =
      `---\n${frontmatter}\n---\n\n` +
      generatedBodyComment(relativeSourcePath) +
      body.trimStart();

    expectedPaths.add(targetRelativePath);
    await syncFile(targetPath, output);
  }
}

async function buildSkills(expectedPaths) {
  const commandFiles = await listFiles(sourceCommandsDir);
  await ensureDir(targetSkillsDir);

  for (const fileName of commandFiles) {
    if (!fileName.endsWith('.md')) {
      continue;
    }

    const skillName = path.basename(fileName, '.md');
    const sourcePath = path.join(sourceCommandsDir, fileName);
    const relativeSourcePath = path.relative(pluginRoot, sourcePath).replace(/\\/g, '/');
    const markdown = await fs.readFile(sourcePath, 'utf8');
    const { frontmatter, body } = extractFrontmatter(markdown, relativeSourcePath);
    const description = getScalar(frontmatter, 'description');
    const argumentHint = getScalar(frontmatter, 'argument-hint');

    if (!description) {
      throw new Error(`Missing description in ${relativeSourcePath}`);
    }

    const skillDir = path.join(targetSkillsDir, skillName);
    const targetPath = path.join(skillDir, 'SKILL.md');
    const targetRelativePath = path.relative(pluginRoot, targetPath).replace(/\\/g, '/');
    const lines = [
      '---',
      `name: ${skillName}`,
      `description: ${description}`,
      'user-invocable: true',
      'disable-model-invocation: true',
    ];

    if (argumentHint) {
      lines.push(`argument-hint: ${argumentHint}`);
    }

    lines.push('---', '', generatedBodyComment(relativeSourcePath).trimEnd(), '', body.trimStart());
    expectedPaths.add(targetRelativePath);
    await syncFile(targetPath, `${lines.join('\n').replace(/\n{3,}/g, '\n\n')}`);
  }
}

async function main() {
  const expectedPaths = new Set([
    'plugin.json',
    'hooks.json',
  ]);

  await buildCopilotManifest();
  await buildHooks();
  await buildAgents(expectedPaths);
  await buildSkills(expectedPaths);
  await pruneDir(targetAgentsDir, expectedPaths);
  await pruneDir(targetSkillsDir, expectedPaths);

  if (updates.length === 0) {
    console.log(checkOnly ? 'Copilot plugin surfaces are up to date.' : 'Copilot plugin surfaces already up to date.');
    return;
  }

  if (checkOnly) {
    console.error('Copilot plugin surfaces are out of date:');
    for (const update of updates.sort()) {
      console.error(`- ${update}`);
    }
    process.exitCode = 1;
    return;
  }

  console.log('Updated Copilot plugin surfaces:');
  for (const update of updates.sort()) {
    console.log(`- ${update}`);
  }
}

await main();
